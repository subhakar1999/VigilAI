# Start the complete local VigilAI stack from any working directory.
Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

$projectDirectory = Split-Path -Parent $PSScriptRoot
$environmentFile = Join-Path $projectDirectory '.env'

function New-LocalSecret {
    param([int] $ByteCount = 32)
    $bytes = New-Object byte[] $ByteCount
    $generator = [System.Security.Cryptography.RandomNumberGenerator]::Create()
    try {
        $generator.GetBytes($bytes)
    } finally {
        $generator.Dispose()
    }
    return ([System.BitConverter]::ToString($bytes)).Replace('-', '').ToLowerInvariant()
}

try {
    if (-not (Get-Command docker -ErrorAction SilentlyContinue)) {
        throw 'Docker was not found. Install Docker Desktop and start it, then run Start-Local.cmd again.'
    }
    & docker compose version *> $null
    if ($LASTEXITCODE -ne 0) {
        throw 'Docker Compose is not available. Start or update Docker Desktop and try again.'
    }
    & docker info *> $null
    if ($LASTEXITCODE -ne 0) {
        throw 'The Docker engine is not running. Start Docker Desktop and try again.'
    }

    if (-not (Test-Path -LiteralPath $environmentFile)) {
        $password = New-LocalSecret 24
        $sessionSecret = New-LocalSecret
        $apiToken = New-LocalSecret
        $settings = @(
            '# Local credentials generated by Start-Local.cmd. Keep this file private.'
            'VIGILAI_ADMIN_USERNAME=admin'
            "VIGILAI_ADMIN_PASSWORD=$password"
            "VIGILAI_AUTH_SECRET=$sessionSecret"
            "VIGILAI_API_TOKEN=$apiToken"
            'VIGILAI_ALLOWED_AGENT_HOSTS=localhost,127.0.0.1,::1,host.docker.internal,test-agents'
            'VIGILAI_COOKIE_SECURE=false'
        )
        # CreateNew prevents overwriting an environment file created concurrently.
        $stream = [System.IO.File]::Open($environmentFile, [System.IO.FileMode]::CreateNew, [System.IO.FileAccess]::Write)
        try {
            $writer = New-Object System.IO.StreamWriter($stream, (New-Object System.Text.UTF8Encoding($false)))
            try { $writer.Write(($settings -join "`n") + "`n") } finally { $writer.Dispose() }
        } finally { $stream.Dispose() }
        Write-Host 'Created local credentials in .env. Open that file to find your username and password.'
    } else {
        Write-Host 'Using the existing .env file.'
    }

    $values = @{}
    foreach ($line in Get-Content -LiteralPath $environmentFile) {
        if ($line -match '^\s*(VIGILAI_[A-Z_]+)\s*=\s*(.*?)\s*$') {
            $values[$Matches[1]] = $Matches[2].Trim('"').Trim("'")
        }
    }
    foreach ($key in @('VIGILAI_ADMIN_USERNAME', 'VIGILAI_ADMIN_PASSWORD', 'VIGILAI_AUTH_SECRET', 'VIGILAI_API_TOKEN')) {
        if (-not $values.ContainsKey($key) -or [string]::IsNullOrWhiteSpace($values[$key]) -or $values[$key] -like 'replace-with-*') {
            throw "The existing .env is missing a valid $key. Update it and run Start-Local.cmd again."
        }
    }
    if ($values['VIGILAI_AUTH_SECRET'].Length -lt 32 -or $values['VIGILAI_API_TOKEN'].Length -lt 32) {
        throw 'VIGILAI_AUTH_SECRET and VIGILAI_API_TOKEN must each contain at least 32 characters.'
    }
    if ($values['VIGILAI_AUTH_SECRET'] -ceq $values['VIGILAI_API_TOKEN']) {
        throw 'Use different values for VIGILAI_AUTH_SECRET and VIGILAI_API_TOKEN in .env.'
    }

    Push-Location $projectDirectory
    try {
        Write-Host 'Building and starting the console, server, worker, and local test agents...'
        & docker compose --profile redteam --profile test-agents up -d --build
        if ($LASTEXITCODE -ne 0) { throw 'Docker Compose could not start the services. Review the output above.' }
        Write-Host ''
        Write-Host 'VigilAI services started. Open http://localhost:3000/console'
        Write-Host 'Sign in with VIGILAI_ADMIN_USERNAME and VIGILAI_ADMIN_PASSWORD from the root .env file.'
        Write-Host 'The first build can take a few minutes; services may need a moment to become ready.'
    } finally {
        Pop-Location
    }
} catch {
    Write-Error $_.Exception.Message
    exit 1
}
